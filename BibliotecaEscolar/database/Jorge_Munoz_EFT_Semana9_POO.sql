--   TABLA USUARIOS
--============================================================
CREATE TABLE USUARIOS (

    ID NUMBER(10)
        GENERATED BY DEFAULT ON NULL AS IDENTITY,

    NOMBRE VARCHAR2(100) NOT NULL,
    RUT VARCHAR2(12) NOT NULL,
    CORREO VARCHAR2(100) NOT NULL,
    CONTRASENA VARCHAR2(255) NOT NULL,
    ROL VARCHAR2(20) NOT NULL,

    CONSTRAINT USUARIOS_PK
        PRIMARY KEY (ID),

    CONSTRAINT USUARIOS_UN_RUT
        UNIQUE (RUT),

    CONSTRAINT USUARIOS_UN_CORREO
        UNIQUE (CORREO),

    CONSTRAINT USUARIOS_CK_ROL
        CHECK (ROL IN ('BIBLIOTECARIO', 'ESTUDIANTE'))
);


-- ============================================================
--   TABLA CATEGORIAS
--   ============================================================
CREATE TABLE CATEGORIAS (
    ID NUMBER(10)
        GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    CONSTRAINT CATEGORIAS_PK
        PRIMARY KEY (ID),

    CONSTRAINT CATEGORIAS_UN_NOMBRE
        UNIQUE (NOMBRE)
);


/* ============================================================
   TABLA ESTUDIANTES
   ============================================================ */
CREATE TABLE ESTUDIANTES (

    ID NUMBER(10)
        GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    RUT VARCHAR2(12) NOT NULL,
    CURSO VARCHAR2(30) NOT NULL,
    CORREO VARCHAR2(100) NOT NULL,
    ID_USUARIO NUMBER(10),
    CONSTRAINT ESTUDIANTES_PK
        PRIMARY KEY (ID),
    CONSTRAINT ESTUDIANTES_UN_RUT
        UNIQUE (RUT),
    CONSTRAINT ESTUDIANTES_UN_CORREO
        UNIQUE (CORREO),
    CONSTRAINT ESTUDIANTES_UN_USUARIO
        UNIQUE (ID_USUARIO),
    CONSTRAINT ESTUDIANTES_FK_USUARIOS
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS(ID)
);


/* ============================================================
   TABLA LIBROS
   ============================================================ */
CREATE TABLE LIBROS (
    ID NUMBER(10)
        GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TITULO VARCHAR2(200) NOT NULL,
    AUTOR VARCHAR2(100) NOT NULL,
    ISBN VARCHAR2(20) NOT NULL,
    EDITORIAL VARCHAR2(100),
    STOCK NUMBER(5) DEFAULT 0 NOT NULL,
    ID_CATEGORIA NUMBER(10) NOT NULL,
    CONSTRAINT LIBROS_PK
        PRIMARY KEY (ID),
    CONSTRAINT LIBROS_UN_ISBN
        UNIQUE (ISBN),
    CONSTRAINT LIBROS_CK_STOCK
        CHECK (STOCK >= 0),
    CONSTRAINT LIBROS_FK_CATEGORIAS
        FOREIGN KEY (ID_CATEGORIA)
        REFERENCES CATEGORIAS(ID)
);


/* ============================================================
   TABLA PRESTAMOS
   ============================================================ */
CREATE TABLE PRESTAMOS (
    ID NUMBER(10)
        GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_ESTUDIANTE NUMBER(10) NOT NULL,
    ID_LIBRO NUMBER(10) NOT NULL,
    FECHA_PRESTAMO DATE DEFAULT SYSDATE NOT NULL,
    FECHA_DEVOLUCION DATE,
    DEVUELTO CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT PRESTAMOS_PK
        PRIMARY KEY (ID),
    CONSTRAINT PRESTAMOS_FK_ESTUDIANTES
        FOREIGN KEY (ID_ESTUDIANTE)
        REFERENCES ESTUDIANTES(ID),
    CONSTRAINT PRESTAMOS_FK_LIBROS
        FOREIGN KEY (ID_LIBRO)
        REFERENCES LIBROS(ID),
    CONSTRAINT PRESTAMOS_CK_DEVUELTO
        CHECK (DEVUELTO IN ('S', 'N')),
    CONSTRAINT PRESTAMOS_CK_FECHAS
        CHECK (
            FECHA_DEVOLUCION IS NULL
            OR FECHA_DEVOLUCION >= FECHA_PRESTAMO
        ),
    CONSTRAINT PRESTAMOS_CK_ESTADO_FECHA
        CHECK (
            (DEVUELTO = 'N' AND FECHA_DEVOLUCION IS NULL)
            OR
            (DEVUELTO = 'S' AND FECHA_DEVOLUCION IS NOT NULL)
        )
);


